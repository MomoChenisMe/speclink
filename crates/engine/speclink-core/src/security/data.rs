//! Validated data and the narrow storage boundary used by Host orchestration.
//! This module has no filesystem, clock, process or network access.
use super::standards::{
    parse_standard, StandardId, StandardSnapshot, StandardSource, PARSER_VERSION,
};
use anyhow::{ensure, Result};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum IntegrityKind {
    SourceTls,
    PinnedDigest,
    Imported,
}

pub struct ValidatedStandard {
    source: StandardSource,
    files: BTreeMap<String, Vec<u8>>,
    snapshot: StandardSnapshot,
    integrity_kind: IntegrityKind,
}

impl ValidatedStandard {
    pub fn new(
        source: StandardSource,
        files: BTreeMap<String, Vec<u8>>,
        integrity_kind: IntegrityKind,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<Self> {
        let snapshot = parse_standard(&source, &files, cancelled)?;
        for file in &source.files {
            ensure!(!cancelled(), "cancelled");
            let bytes = files.get(&file.name);
            if source.standard_id == StandardId::Cwe
                && file.name.ends_with(".xml.zip")
                && integrity_kind == IntegrityKind::Imported
                && bytes.is_none()
            {
                continue;
            }
            let bytes = bytes
                .ok_or_else(|| anyhow::anyhow!("invalid_package: missing declared source file"))?;
            if let Some(expected) = &file.sha256 {
                ensure!(
                    sha256(bytes).eq_ignore_ascii_case(expected),
                    "integrity_error: source fingerprint mismatch"
                );
            }
        }
        if integrity_kind == IntegrityKind::PinnedDigest {
            ensure!(
                source.files.iter().all(|f| f.sha256.is_some()),
                "integrity_error: no pinned fingerprint for every source"
            );
        }
        Ok(Self {
            source,
            files,
            snapshot,
            integrity_kind,
        })
    }
    pub fn source(&self) -> &StandardSource {
        &self.source
    }
    pub fn files(&self) -> &BTreeMap<String, Vec<u8>> {
        &self.files
    }
    pub fn snapshot(&self) -> &StandardSnapshot {
        &self.snapshot
    }

    pub fn metadata(&self, generation: String, downloaded_at: String) -> Result<StandardMetadata> {
        let mut combined = Sha256::new();
        let mut hashes = BTreeMap::new();
        for (name, bytes) in &self.files {
            combined.update((name.len() as u64).to_be_bytes());
            combined.update(name.as_bytes());
            combined.update((bytes.len() as u64).to_be_bytes());
            combined.update(bytes);
            hashes.insert(name.clone(), sha256(bytes));
        }
        let source = &self.source;
        Ok(StandardMetadata {
            standard_id: source.standard_id, version: source.version.clone(), source_url: source.source_url.clone(),
            license_name: source.license_name.clone(), license_url: source.license_url.clone(), attribution: source.attribution.clone(),
            downloaded_at, sha256: format!("{:x}", combined.finalize()), installed_status: "installed".into(), source_format: source.source_format.clone(),
            generation, source_revision: source.source_revision.clone(), integrity_kind: self.integrity_kind, parser_version: PARSER_VERSION.into(),
            files: hashes, parsed_sha256: sha256(&serde_json::to_vec(&self.snapshot)?),
            modification_notice: "Parsed representation generated by SpecLink. Original source and license retained; no translation. Data is not relicensed as SpecLink MIT code.".into(),
        })
    }
}

pub fn sha256(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StandardMetadata {
    pub standard_id: StandardId,
    pub version: String,
    pub source_url: String,
    pub license_name: String,
    pub license_url: String,
    pub attribution: String,
    pub downloaded_at: String,
    pub sha256: String,
    pub installed_status: String,
    pub source_format: String,
    pub generation: String,
    pub source_revision: String,
    pub integrity_kind: IntegrityKind,
    pub parser_version: String,
    pub files: BTreeMap<String, String>,
    pub parsed_sha256: String,
    pub modification_notice: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct InstalledStandard {
    pub metadata: StandardMetadata,
    pub snapshot: StandardSnapshot,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct InstallReceipt {
    pub standard_id: StandardId,
    pub version: String,
    pub installed_status: String,
    pub sha256: String,
    pub source_revision: String,
    pub integrity_kind: IntegrityKind,
    pub generation: String,
    pub warnings: Vec<String>,
}

pub trait StandardInstall: Send {
    fn commit(self: Box<Self>, standard: ValidatedStandard) -> Result<InstallReceipt> {
        self.commit_cancellable(standard, &|| false)
    }
    fn commit_cancellable(
        self: Box<Self>,
        standard: ValidatedStandard,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<InstallReceipt>;
}

pub trait StandardRepository: Send + Sync {
    /// A snapshot of a policy actually read by this device. Never contacts remote stores.
    fn remember_policy(&self, key: &str, policy: &super::policy::SecurityPolicy) -> Result<()>;
    fn remove(&self, standard: StandardId, version: &str) -> Result<()>;
    /// Hold for the entire review, including after the data has been read into memory.
    fn pin(&self, standard: StandardId, version: &str) -> Result<Box<dyn StandardPin>>;
    fn import_package(
        &self,
        path: &std::path::Path,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<InstallReceipt>;
    fn versions(&self) -> Result<Vec<(StandardId, String)>>;
    fn read(&self, standard: StandardId, version: &str) -> Result<Option<InstalledStandard>>;
    fn begin_install(
        &self,
        standard: StandardId,
        version: &str,
    ) -> Result<Box<dyn StandardInstall>>;
}

pub trait StandardPin: Send + Sync {}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PackageManifest {
    pub format_version: u8,
    pub standard_id: StandardId,
    pub version: String,
    pub source_revision: String,
    pub source_url: String,
    pub source_format: String,
    pub license_name: String,
    pub license_url: String,
    pub attribution: String,
    pub entries: Vec<PackageEntry>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PackageEntry {
    pub name: String,
    pub sha256: String,
}

impl PackageManifest {
    pub fn source(&self) -> Result<StandardSource> {
        use super::standards::{standard_source, valid_data_name, MAX_PACKAGE_ENTRIES};
        ensure!(
            self.format_version == 1
                && !self.entries.is_empty()
                && self.entries.len() < MAX_PACKAGE_ENTRIES,
            "invalid_package: manifest version or entry count"
        );
        let source = standard_source(self.standard_id, &self.version)?;
        ensure!(
            self.source_revision == source.source_revision
                && self.source_url == source.source_url
                && self.source_format == source.source_format,
            "invalid_package: source metadata mismatch"
        );
        ensure!(
            self.license_name == source.license_name
                && self.license_url == source.license_url
                && self.attribution == source.attribution,
            "license_missing: source license and attribution must be retained"
        );
        let mut names = std::collections::BTreeSet::new();
        let cwe_xml = format!("raw/cwec_v{}.xml", self.version);
        for entry in &self.entries {
            ensure!(
                valid_data_name(&entry.name) && names.insert(entry.name.to_ascii_lowercase()),
                "invalid_package: unsafe or duplicate manifest path"
            );
            ensure!(
                source.files.iter().any(|f| f.name == entry.name)
                    || (self.standard_id == StandardId::Cwe && entry.name == cwe_xml),
                "invalid_package: unexpected data file"
            );
            ensure!(
                entry.sha256.len() == 64 && entry.sha256.bytes().all(|b| b.is_ascii_hexdigit()),
                "invalid_package: manifest fingerprint"
            );
        }
        ensure!(names.contains("license"), "license_missing");
        Ok(source)
    }
}
